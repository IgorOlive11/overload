/* ícones em pixel art: cada linha é uma fileira de pixels */
function pix(rows, w){
  const H = rows.length, W = rows[0].length; let r = '';
  rows.forEach((row, y) => { let x = 0; while (x < W){ if (row[x] === '#'){ let e = x; while (e < W && row[e] === '#') e++; r += `<rect x="${x}" y="${y}" width="${e - x}" height="1"/>`; x = e; } else x++; } });
  return `<svg viewBox="0 0 ${W} ${H}" width="${w}" height="${Math.round(w*H/W)}" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true">${r}</svg>`;
}
